"""Private workspace deadline table (root/dates.md) and user deadline overrides.

Only the ``user`` column of dates.md is input. Website, subject and name cells are
display copies of untrusted portal data and are never read back as authority.
"""

from __future__ import annotations

import json
import re
from datetime import date
from pathlib import Path
from typing import TYPE_CHECKING

from lab_auto.files import atomic_write_text

if TYPE_CHECKING:
    from lab_auto.models import WorkRecord

UNSPECIFIED = "UNSPECIFIED"
DATES_FILE = "dates.md"

_MISSING_DEADLINES = frozenset({
    "", "-", "—", "–", "−", "не указана", "не указан", "не указано", UNSPECIFIED.casefold(),
})
_ISO_DATE = re.compile(r"(\d{4})-(\d{2})-(\d{2})")
_RU_DATE = re.compile(r"(\d{1,2})\.(\d{1,2})\.(\d{4})")
_SEPARATOR_CELL = re.compile(r":?-{3,}:?")
_HEADERS = ("work_id", "Дисциплина", "Задание", "user", "website")
_BASELINE_PREFIX = "<!-- lab-auto-dates-baseline: "


class DatesFileError(ValueError):
    """Raised when dates.md user edits are malformed or would be lost."""


def normalize_deadline(value: str | None) -> str | None:
    """Return an ISO date, None for an explicitly missing deadline, or raise ValueError."""
    if value is None:
        return None
    text = " ".join(str(value).split())
    if text.casefold() in _MISSING_DEADLINES:
        return None
    if match := _ISO_DATE.fullmatch(text):
        year, month, day = match.groups()
    elif match := _RU_DATE.fullmatch(text):
        day, month, year = match.groups()
    else:
        raise ValueError(f"Invalid deadline {text!r}: expected YYYY-MM-DD, DD.MM.YYYY or {UNSPECIFIED}.")
    try:
        return date(int(year), int(month), int(day)).isoformat()
    except ValueError as exc:
        raise ValueError(f"Invalid deadline {text!r}: {exc}.") from None


def normalize_user_due_date(value: str) -> str:
    """Normalize an explicit user override: ISO date, or UNSPECIFIED for an explicit no-date."""
    return normalize_deadline(value) or UNSPECIFIED


def website_due_date(value: str | None) -> str | None:
    """Website deadline as ISO; unparseable portal text is treated as no deadline."""
    try:
        return normalize_deadline(value)
    except ValueError:
        return None


def dates_path(root: Path) -> Path:
    return root / DATES_FILE


def _cell(value: object) -> str:
    text = " ".join(str(value).split())
    for char, escaped in (("&", "&amp;"), ("<", "&lt;"), (">", "&gt;"), ("|", "&#124;"), ("`", "&#96;")):
        text = text.replace(char, escaped)
    return text


def _website_cell(work: WorkRecord) -> str:
    try:
        return normalize_deadline(work.due_date) or UNSPECIFIED
    except ValueError:
        return _cell(work.due_date)


def _table(works: list[WorkRecord]) -> list[str]:
    if not works:
        return ["Нет."]
    lines = ["| " + " | ".join(_HEADERS) + " |", "| " + " | ".join("---" for _ in _HEADERS) + " |"]
    for work in works:
        cells = (
            _cell(work.work_id),
            _cell(work.subject),
            _cell(work.name),
            work.effective_due_date or UNSPECIFIED,
            _website_cell(work),
        )
        lines.append("| " + " | ".join(cells) + " |")
    return lines


def render_dates_markdown(works: list[WorkRecord]) -> str:
    active = [work for work in works if not work.archived]
    dated = sorted(
        (work for work in active if work.effective_due_date),
        key=lambda work: (work.effective_due_date, work.subject.casefold(), work.name.casefold(), work.work_id),
    )
    undated = sorted(
        (work for work in active if not work.effective_due_date),
        key=lambda work: (work.subject.casefold(), work.name.casefold(), work.work_id),
    )
    # Keep the last rendered user values separate from editable display columns.
    # This distinguishes a real edit from an old view left after a website update.
    baseline = json.dumps(
        {work.work_id: work.effective_due_date or UNSPECIFIED for work in active},
        ensure_ascii=True, sort_keys=True, separators=(",", ":"),
    ).replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    lines = [
        "<!-- Generated by lab-auto. Private workspace data: never commit or publish this file. -->",
        f"<!-- Edit only the user column (YYYY-MM-DD, DD.MM.YYYY or {UNSPECIFIED}); "
        "other columns are regenerated. `lab-auto dates reset <work_id>` follows the website again. -->",
        f"{_BASELINE_PREFIX}{baseline} -->",
        "# Дедлайны",
        "",
        "## С датой",
        "",
        *_table(dated),
        "",
        f"## Без даты ({UNSPECIFIED})",
        "",
        *_table(undated),
    ]
    return "\n".join(lines) + "\n"


def _read_user_rows(path: Path) -> tuple[dict[str, list[tuple[int, str]]], dict[str, str]]:
    """Read user edits and their generated baseline, never website display values."""
    rows: dict[str, list[tuple[int, str]]] = {}
    baseline: dict[str, str] = {}
    if not path.is_file():
        return rows, baseline
    headers: list[str] | None = None
    baseline_seen = False
    for lineno, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        stripped = line.strip()
        if stripped.startswith(_BASELINE_PREFIX):
            if baseline_seen or not stripped.endswith(" -->"):
                raise DatesFileError(f"{path}:{lineno}: invalid generated deadline baseline.")
            try:
                decoded = json.loads(stripped[len(_BASELINE_PREFIX):-4])
            except json.JSONDecodeError:
                raise DatesFileError(f"{path}:{lineno}: invalid generated deadline baseline.") from None
            if not isinstance(decoded, dict) or not all(
                isinstance(key, str) and isinstance(value, str) for key, value in decoded.items()
            ):
                raise DatesFileError(f"{path}:{lineno}: invalid generated deadline baseline.")
            baseline = decoded
            baseline_seen = True
            continue
        # Keep the last header across prose so moved or appended rows still count.
        if not stripped.startswith("|"):
            continue
        body = stripped[1:-1] if stripped.endswith("|") and len(stripped) > 1 else stripped[1:]
        cells = [cell.strip().strip("`").strip() for cell in body.split("|")]
        if "work_id" in cells and "user" in cells:
            headers = cells
            continue
        if headers is None or all(not cell or _SEPARATOR_CELL.fullmatch(cell) for cell in cells):
            continue
        if len(cells) > len(headers):
            raise DatesFileError(f"{path}:{lineno}: row has more cells than its header; do not type '|' in cells.")
        row = dict(zip(headers, cells + [""] * (len(headers) - len(cells))))
        work_id = row["work_id"]
        if work_id:
            rows.setdefault(work_id, []).append((lineno, row["user"]))
    return rows, baseline


def pending_user_due_dates(path: Path, works: list[WorkRecord]) -> dict[str, str]:
    """Compare user cells with the last generated view, preserving inherited defaults."""
    rows, baseline = _read_user_rows(path)
    pending: dict[str, str] = {}
    for work in works:
        if work.archived:
            continue
        entries = rows.get(_cell(work.work_id))
        if not entries:
            continue
        if len(entries) > 1:
            lines = ", ".join(str(lineno) for lineno, _ in entries)
            raise DatesFileError(f"{path}: duplicate rows for {work.work_id} on lines {lines}; keep one.")
        lineno, user_cell = entries[0]
        try:
            value = normalize_deadline(user_cell)
            previous = normalize_deadline(baseline[work.work_id]) if work.work_id in baseline else work.effective_due_date
        except ValueError as exc:
            raise DatesFileError(f"{path}:{lineno}: invalid user date for {work.work_id}: {exc}") from None
        if value != previous:
            pending[work.work_id] = value or UNSPECIFIED
    return pending


def apply_user_edits(root: Path, works: list[WorkRecord]) -> None:
    """Apply dates.md user-column edits to freshly loaded records in place."""
    pending = pending_user_due_dates(dates_path(root), works)
    for work in works:
        if work.work_id in pending:
            work.user_due_date = pending[work.work_id]


def write_dates_markdown(root: Path, works: list[WorkRecord]) -> Path:
    path = dates_path(root)
    atomic_write_text(path, render_dates_markdown(works))
    return path


def _regenerate_unlocked(root: Path, works: list[WorkRecord]) -> None:
    from lab_auto.state import active_works, generate_markdown_views, generate_task_markdown, save_state_unlocked
    from lab_auto.subject_materials import load_subject_materials

    save_state_unlocked(root, works)
    generate_markdown_views(root, works)
    materials = load_subject_materials(root)
    for work in active_works(works):
        if work.folder.is_dir():
            generate_task_markdown(work, materials, root=root)


def refresh_dates(root: Path) -> Path:
    """Persist dates.md user edits and regenerate deadline views offline."""
    from lab_auto.state import load_state_unlocked, locked_workspace

    with locked_workspace(root):
        works = load_state_unlocked(root)
        _regenerate_unlocked(root, works)
    return dates_path(root)


def set_user_due_date(root: Path, work_ref: str, value: str | None) -> WorkRecord:
    """None follows the website; UNSPECIFIED explicitly clears; a date pins an override."""
    from lab_auto.state import load_state_unlocked, locked_workspace
    from lab_auto.workspace import find_work_in_list

    user_due_date = None if value is None else normalize_user_due_date(value)
    with locked_workspace(root):
        works, work = find_work_in_list(root, load_state_unlocked(root), work_ref)
        work.user_due_date = user_due_date
        _regenerate_unlocked(root, works)
    return work
